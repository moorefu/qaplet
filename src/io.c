void qaplet_io_collect(qaplet_runtime *r) {
  pthread_mutex_lock(&r->mutex);qaplet_io_pool *p=r->io_pool;
  if(p && p->operations)for(uint64_t i=0;i<r->m2_limits.operations;++i){io_operation *o=&p->operations[i];if(!o->active)continue;
    if(IsWindows() && !o->native_endpoint->terminal && o->physical && o->exited){
      cancel_native_locked(r,o);
      /* Only a signalled native completion proves the kernel stopped using
       * OVERLAPPED/data. A failed or incomplete check retains ownership. */
      uint32_t waited=WaitForSingleObject(o->overlapped.hEvent,0);
      if(waited==0){uint32_t n=0;int ok=GetOverlappedResult(o->endpoint->handle,&o->overlapped,&n,false),error=ok ? 0 : GetLastError();
        if(ok || error!=996)complete_locked(r,o,n,error==109 && !o->writing ? 0 : error,QAPLET_ERROR_DOMAIN_WIN32,error==109 && !o->writing);
      }else if(waited!=258)cleanup_locked(r,GetLastError(),QAPLET_ERROR_DOMAIN_WIN32);
    }
    if(o->helper && !o->native_endpoint->terminal && o->exited && !o->join_attempted){
      o->join_attempted=1;pthread_mutex_unlock(&r->mutex);int error=pthread_tryjoin_np(o->thread,NULL);pthread_mutex_lock(&r->mutex);
      if(error==EBUSY)o->join_attempted=0;
      else if(error)cleanup_locked(r,error,QAPLET_ERROR_DOMAIN_ERRNO);
      else {o->helper=0;if(o->native_endpoint->terminal)--o->native_endpoint->terminal_helpers;--r->native_retained;if(IsWindows())--r->native_handles;--r->helper_threads;r->helper_stack_bytes-=r->m2_limits.helper_stack_bytes;--p->snapshot.helper_threads;p->snapshot.helper_stack_bytes-=r->m2_limits.helper_stack_bytes;}
    }
    if(!o->helper && !o->physical)handle_closed_locked(r,&o->overlapped.hEvent);
    if((o->released || p->closing) && !o->physical && !o->helper && !o->handoff)retire_operation_locked(r,o);
  }
  if(p)for(uint64_t i=0;i<r->m2_limits.native_handles;++i){io_endpoint *e=&p->endpoints[i];
    if(e->active && e->ended && !e->pending){close_endpoint_locked(r,e);if(!e->lease_active && (e->detached || p->closing) && !e->handoffs){e->active=0;--p->snapshot.endpoints;--r->reactor_registrations;}}
  }
  if(p && p->terminal_joiner_active && p->terminal_joiner_exited && !p->terminal_joiner_joining){
    p->terminal_joiner_joining=1;pthread_mutex_unlock(&r->mutex);int error=pthread_tryjoin_np(p->terminal_joiner,NULL);pthread_mutex_lock(&r->mutex);
    if(error==EBUSY)p->terminal_joiner_joining=0;
    else if(error)cleanup_locked(r,error,QAPLET_ERROR_DOMAIN_ERRNO);
    else {p->terminal_joiner_active=0;--r->native_retained;--r->native_handles;--r->helper_threads;r->helper_stack_bytes-=r->m2_limits.helper_stack_bytes;--p->snapshot.helper_threads;p->snapshot.helper_stack_bytes-=r->m2_limits.helper_stack_bytes;}
  }
  if(p && p->closing && !p->snapshot.endpoints && !p->snapshot.operations && !p->snapshot.helper_threads){
    free_locked(r,p->endpoints,p->endpoint_bytes);free_locked(r,p->operations,p->operation_bytes);free_locked(r,p->pollfds,p->poll_bytes);free_locked(r,p,sizeof(*p));r->io_pool=NULL;--r->native_retained;
  }
  if(r->loop_closed && !r->native_retained && !r->notify_inflight && !r->native_handles && !r->native_uncertain_handles)r->native_state=QAPLET_NATIVE_QUIESCENT;
  pthread_mutex_unlock(&r->mutex);
}
void qaplet_io_shutdown(qaplet_runtime *r,int closing) {
  qaplet_js_io_shutdown(r);
  pthread_mutex_lock(&r->mutex);qaplet_io_pool *p=r->io_pool;
  if(p){
    if(closing)p->closing=1;
    if(p->operations)for(uint64_t i=0;i<r->m2_limits.operations;++i){io_operation *o=&p->operations[i];if(!o->active)continue;
      cancel_locked(r,o);if(closing)o->released=1;
      if(o->handoff){o->handoff=0;--p->snapshot.pending_handoffs;--o->endpoint->handoffs;/* Keep endpoint pointer for physical completion. */}
    }
    for(uint64_t i=0;i<r->m2_limits.native_handles;++i)if(p->endpoints[i].active)close_endpoint_locked(r,&p->endpoints[i]);
    pthread_cond_broadcast(&r->native_condition);
  }
  pthread_mutex_unlock(&r->mutex);qaplet_io_collect(r);
}
